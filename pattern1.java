public class pattern1 {
    public static void main(String[] args) {
        int n=4;
        for(int i=1;i<n+1;i++){
            for(int j=1;j<n+1;j++){
                System.out.print("*"); //System.out.print() = print("*",end="") in python, where this means print on the same line
            }
            System.out.println();
        }
    }
        
    }
 